import json
import subprocess

langs = ['en', 'ta', 'hi', 'ml', 'te']

# 1. Load current locales in abinav6
locales = {}
for lang in langs:
    with open(f'src/locales/{lang}.json', 'r', encoding='utf-8') as f:
        locales[lang] = json.load(f)

# 2. Load sudharsan locales
sud_locales = {}
for lang in langs:
    raw = subprocess.check_output(['git', 'show', f'sudharsan:src/data/lang/ui_{lang}.json'], encoding='utf-8')
    sud_locales[lang] = json.loads(raw)

# 3. Find keys from sudharsan missing in abinav6 en.json
missing_keys = [k for k in sud_locales['en'].keys() if k not in locales['en']]

print(f"Adding {len(missing_keys)} missing keys from sudharsan...")
for k in missing_keys:
    for lang in langs:
        val = sud_locales[lang].get(k)
        if not val:
            val = sud_locales['en'].get(k, k)
        locales[lang][k] = val

